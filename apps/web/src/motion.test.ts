import { afterEach, expect, it, vi } from 'vitest';
import { enableMotion, ShakeDetector } from './motion';
afterEach(() => { vi.unstubAllGlobals(); vi.useRealTimers(); });
it('requires two strong separated peaks; rejects normal motion, bad readings and a shake burst', () => {
  const detector = new ShakeDetector();
  expect(detector.sample(0, 0, 9.8, 0)).toBe(false);
  expect(detector.sample(1, 1, 10, 100)).toBe(false);
  expect(detector.sample(30, 0, 10, 200)).toBe(false);
  expect(detector.sample(-30, 0, 10, 250)).toBe(false);
  expect(detector.sample(30, 0, 10, 400)).toBe(true);
  expect(detector.sample(-30, 0, 10, 600)).toBe(false);
  expect(detector.sample(NaN, 0, 0, 20_000)).toBe(false);
  expect(detector.sample(null, 0, 0, 20_000)).toBe(false);
  expect(detector.sample(30, 0, 10, 10_600)).toBe(false);
  expect(detector.sample(-30, 0, 10, 10_800)).toBe(true);
});
it('requests iOS permission immediately in the tap, handles denial and unsupported contexts', async () => {
  const unavailable = vi.fn(), shake = vi.fn(), permission = vi.fn().mockResolvedValue('denied');
  vi.stubGlobal('isSecureContext', true);
  vi.stubGlobal('DeviceMotionEvent', { requestPermission: permission });
  const result = enableMotion(shake, unavailable);
  expect(permission).toHaveBeenCalledOnce();
  const stop = await result; stop();
  expect(unavailable).toHaveBeenCalledOnce();
  expect(shake).not.toHaveBeenCalled();
  vi.stubGlobal('DeviceMotionEvent', undefined);
  (await enableMotion(shake, unavailable))();
  expect(unavailable).toHaveBeenCalledTimes(2);
});
it('detects Android motion, falls back after absent/null readings, and removes all listeners', async () => {
  vi.useFakeTimers(); vi.stubGlobal('isSecureContext', true); vi.stubGlobal('DeviceMotionEvent', {});
  const unavailable = vi.fn(), shake = vi.fn();
  let time = 0; vi.spyOn(performance, 'now').mockImplementation(() => time);
  const emit = (x: number | null, t: number) => { time = t; window.dispatchEvent(Object.assign(new Event('devicemotion'), { accelerationIncludingGravity: { x, y: 0, z: 9.8 } })); };
  const stop = await enableMotion(shake, unavailable);
  emit(null, 0); await vi.advanceTimersByTimeAsync(4000);
  expect(unavailable).toHaveBeenCalledOnce();
  emit(0, 0); emit(30, 200); emit(-30, 400);
  expect(shake).toHaveBeenCalledOnce(); stop(); emit(30, 20_000); emit(-30, 20_200);
  expect(shake).toHaveBeenCalledOnce();
  vi.restoreAllMocks();
});
